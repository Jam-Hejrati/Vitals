// Generates src/data/replacements.ts from the e18e `module-replacements` dataset (MIT).
// Usage: pnpm replacements:update   (after bumping the module-replacements devDependency)
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const root = dirname(require.resolve('module-replacements/package.json'));
const { version } = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));

// Most opinionated first: the curated "preferred" list wins over the broader ones.
const manifests = ['preferred', 'native', 'micro-utilities'];
const MAX_PER_MODULE = 5;

const suggestions = new Map();
for (const file of manifests) {
  const { mappings, replacements } = JSON.parse(
    await readFile(join(root, 'manifests', `${file}.json`), 'utf8'),
  );
  for (const mapping of Object.values(mappings)) {
    const list = suggestions.get(mapping.moduleName) ?? [];
    for (const id of mapping.replacements) {
      const suggestion = toSuggestion(replacements[id]);
      if (
        suggestion &&
        !list.some((s) => s.kind === suggestion.kind && s.name === suggestion.name)
      ) {
        list.push(suggestion);
      }
    }
    if (list.length > 0) suggestions.set(mapping.moduleName, list);
  }
}

function toSuggestion(replacement) {
  if (!replacement) return undefined;
  switch (replacement.type) {
    case 'documented':
      return { kind: 'package', name: replacement.replacementModule };
    case 'native': {
      const node = replacement.engines?.find((e) => e.engine === 'nodejs')?.minVersion;
      const mdn = replacement.url?.type === 'mdn' ? replacement.url.id : undefined;
      return {
        kind: 'native',
        name: replacement.id.replaceAll('_', ' '),
        ...(node && { node }),
        ...(mdn && { url: `https://developer.mozilla.org/en-US/docs/${mdn}` }),
      };
    }
    case 'removal':
      return { kind: 'removal', name: 'remove it', note: replacement.description };
    case 'simple':
      return { kind: 'snippet', name: 'an inline snippet', note: replacement.description };
    default:
      return undefined;
  }
}

const body = [...suggestions]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(
    ([name, list]) =>
      `  ${JSON.stringify(name)}: ${JSON.stringify(list.slice(0, MAX_PER_MODULE))},`,
  )
  .join('\n');

await writeFile(
  new URL('../src/data/replacements.ts', import.meta.url),
  `// Generated by scripts/update-replacements.mjs from module-replacements@${version}\n` +
    `// (https://github.com/es-tooling/module-replacements, MIT, by the e18e community). Do not edit.\n` +
    `import type { Suggestion } from '../replacements.js';\n\n` +
    `export const REPLACEMENTS: Record<string, Suggestion[]> = {\n${body}\n};\n`,
);
console.log(`Wrote ${suggestions.size} modules from module-replacements@${version}`);
